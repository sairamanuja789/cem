"""Writes docs/unsourced.md: every line in product and platform code or data marked UNSOURCED.

CLAUDE.md rule 7: an engineering value without a known source is marked UNSOURCED and reported.
This register makes that backlog visible to the owner; tests/python/test_unsourced_register.py
fails when the committed register is out of date.
Run: uv run python scripts/gen_unsourced_register.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTER = ROOT / "docs" / "unsourced.md"
SCANNED = ("data", "kernel", "python", "schemas")
SUFFIXES = {".py", ".pyi", ".hpp", ".cpp", ".h", ".yaml", ".yml", ".json", ".txt", ".cmake"}
MARKER = "UNSOURCED"


def is_test(path: Path) -> bool:
    parts = path.relative_to(ROOT).parts
    return any(p in ("tests", "testing") for p in parts) or path.name.startswith("test_")


def entries() -> list[tuple[str, str]]:
    found = []
    for top in SCANNED:
        for path in sorted((ROOT / top).rglob("*")):
            if path.suffix not in SUFFIXES or not path.is_file() or is_test(path):
                continue
            for line in path.read_text(encoding="utf-8").splitlines():
                if MARKER in line:
                    found.append((path.relative_to(ROOT).as_posix(), line.strip()))
    return found


def render() -> str:
    found = entries()
    lines = [
        "# UNSOURCED register",
        "",
        "GENERATED by `scripts/gen_unsourced_register.py`; never edit. CI fails when it is stale.",
        "",
        "Every line in `data/`, `kernel/`, `python/` and `schemas/` (tests excluded) with",
        "the UNSOURCED marker (CLAUDE.md rule 7). Some lines define or explain the marker;",
        "the rest are values or models still waiting for a cited source.",
        "",
        f"{len(found)} line(s) in {len({f for f, _ in found})} file(s).",
        "",
    ]
    current = None
    for file, text in found:
        if file != current:
            if current is not None:
                lines.append("")
            lines += [f"## `{file}`", ""]
            current = file
        lines.append(f"- `{text.replace('`', "'")}`")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    REGISTER.write_text(render(), encoding="utf-8")
    sys.stdout.write(f"wrote {REGISTER.relative_to(ROOT)}\n")
